#!/usr/bin/env python3
"""Check the preserved report evidence, not a diffoscope execution."""
from pathlib import Path
import hashlib
import json
import re
import struct

root = Path(__file__).resolve().parent
def load(name):
    return json.loads((root / name).read_text())

data = (root / 'native.html').read_bytes()
assert len(data) == 1117354
assert hashlib.sha256(data).hexdigest() == load('context.json')['native_sha256']
for entry in load('source/blobs.json'):
    payload = (root / 'source' / entry['path']).read_bytes()
    assert len(payload) == entry['bytes']
    assert hashlib.sha1(b'blob ' + str(len(payload)).encode() + b'\0' + payload).hexdigest() == entry['blob']
initial = load('browser/initial-dom.json')
member = load('browser/member-dom.json')
sql = load('browser/sql-dom.json')
assert len(initial['headers']) == 8 and initial['footer'] == 'Generated by diffoscope 28'
assert member['listing']['class'] == 'diffunmodified'
assert member['listing']['cells'][1] == member['listing']['cells'][3]
assert '3421' in member['listing']['cells'][1]
assert len(member['changes']) == 1
def normalize(text):
    return text.replace('\u200b', '').replace('·', ' ').strip()
cells = member['changes'][0]['cells']
assert normalize(cells[1]) == '<label>5.0.6</label>'
assert normalize(cells[3]) == '<label>5.0.7</label>'
counts = []
for row in sql['markers']:
    assert row['controls'] == 0
    counts.append([int(re.fullmatch(r'\[ (\d+) lines removed \]', normalize(row['cells'][i]))[1]) for i in (1, 3)])
assert counts == [[15462,15387],[386,390],[31967,32027],[9300,9314]]
assert sql['scripts'] == sql['buttons'] == 0
assert not re.search(br'<script\b', data, re.I)
assert sql['hash'] == '#defaults/rulesets.sqlite/sqlite3 {} .dump'
images = []
for path in sorted((root / 'browser').glob('*.png')):
    png = path.read_bytes()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    assert struct.unpack('>II', png[16:24]) == (1279, 784)
    images.append(path.name)
assert len(images) == 3
links = 0
for target in re.findall(r'\]\(([^)]+)\)', (root / 'README.md').read_text()):
    if not target.startswith(('https:', 'http:')):
        assert (root / target.split('#')[0]).exists(), target
        links += 1
print(json.dumps({'status':'pass','native_bytes':len(data),'source_blobs':5,
                  'headers':8,'same_listing_different_reported_content':True,
                  'omitted_line_pairs':counts,'images':images,'local_links':links,
                  'native_cli_executed':False,'exact_generator_commit_proven':False},indent=2))
